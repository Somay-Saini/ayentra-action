from __future__ import annotations

from pathlib import Path
from typing import Any

from ayentra.dogfood import synthesize_business_risk, synthesize_plain_english_bug


def _format_relative_path(path: Path, root: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.resolve().as_posix()


def to_sarif(
    check_results: list[tuple[Path, Any, list[Any]]] | tuple[Path, Any, list[Any]],
    root_dir: Path | None = None,
) -> dict[str, Any]:
    """Generate OASIS SARIF 2.1.0 report dictionary from verification results."""
    if isinstance(check_results, tuple):
        check_results = [check_results]
    if root_dir is None:
        root_dir = Path.cwd()

    rules = [
        {
            "id": "AYENTRA001",
            "name": "InvariantViolation",
            "shortDescription": {
                "text": "Explicit behavioral invariant violated under property-based testing",
            },
            "fullDescription": {
                "text": "An explicit behavioral contract or domain invariant failed verification under deterministic shrinking.",
            },
            "defaultConfiguration": {
                "level": "error",
            },
            "help": {
                "text": "Inspect the counterexample and repair candidate generated by Ayentra. Run 'ayentra apply-patch <file> --yes' to apply the verified patch.",
                "markdown": "Inspect the counterexample and repair candidate generated by Ayentra. Run `ayentra apply-patch <file> --yes` to apply the verified patch.",
            },
            "properties": {
                "tags": ["correctness", "security", "invariants"],
                "precision": "very-high",
            },
        }
    ]

    sarif_results: list[dict[str, Any]] = []

    for path, engine_res, patch_results in check_results:
        for idx, violation in enumerate(engine_res.violations):
            patch = patch_results[idx] if idx < len(patch_results) else None
            plain_bug = synthesize_plain_english_bug(violation)
            biz_risk = synthesize_business_risk(violation)

            target_file = (
                Path(violation.invariant.filepath)
                if violation.invariant.filepath and violation.invariant.filepath != "<unknown>"
                else path
            )
            rel_uri = _format_relative_path(target_file, root_dir)
            line_no = violation.invariant.lineno if violation.invariant.lineno else 1
            message_text = f"Invariant violation in {violation.failing_target}: {plain_bug}. Risk: {biz_risk}."

            res_obj: dict[str, Any] = {
                "ruleId": "AYENTRA001",
                "ruleIndex": 0,
                "level": "error",
                "message": {
                    "text": message_text,
                },
                "locations": [
                    {
                        "physicalLocation": {
                            "artifactLocation": {
                                "uri": rel_uri,
                                "uriBaseId": "%SRCROOT%",
                            },
                            "region": {
                                "startLine": line_no,
                                "startColumn": 1,
                            },
                        }
                    }
                ],
                "properties": {
                    "failing_target": violation.failing_target,
                    "counterexample": violation.counterexample,
                    "seed": violation.seed,
                },
            }



            sarif_results.append(res_obj)

    return {
        "$schema": "https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "Ayentra",
                        "version": "0.1.0",
                        "informationUri": "https://github.com/ayentra/ayentra",
                        "rules": rules,
                    }
                },
                "results": sarif_results,
            }
        ],
    }


build_sarif_report = to_sarif
